export function getSampleTextById(id) {
  return SAMPLE_TEXTS.find((sample) => sample.id === id) || null;
}

export function getFilteredSampleTexts(grade, difficulty, length) {
  return SAMPLE_TEXTS.filter((sample) => {
    const matchesGrade = grade ? sample.grade === grade : true;
    const matchesDifficulty = difficulty ? sample.difficulty === difficulty : true;
    const matchesLength = length ? sample.length === length : true;
    return matchesGrade && matchesDifficulty && matchesLength;
  });
}

export function getSampleTextbookAttribution(sampleOrId) {
  const sample = typeof sampleOrId === "string"
    ? getSampleTextById(sampleOrId)
    : sampleOrId;

  if (!sample || sample.sourceType !== "textbook") {
    return null;
  }

  return {
    type: "textbook",
    title: sample.title,
    bookTitle: sample.bookTitle,
    pageLabel: sample.source,
  };
}

